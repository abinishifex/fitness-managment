/**
 * Canonical exercise catalogue seed (Day 2).
 * Substitutions reference other entries by `slug` and are resolved to ObjectIds after insert.
 */

const mongoose = require('mongoose');
const { Exercise } = require('../models');

async function seedExercises() {
  console.log("Seeding exercises...");

  for (const ex of EXERCISE_SEED) {
    await Exercise.findOneAndUpdate(
      { name: ex.name },
      ex,
      { upsert: true, new: true }
    );
  }

  // Drop retired catalogue entries that upserts cannot remove.
  await Exercise.deleteMany({ slug: { $in: ['dead-bug'] } });

  console.log("✅ Exercises seeded!");
}
function slugify(name) {
  return name
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-+|-+$/g, '');
}

